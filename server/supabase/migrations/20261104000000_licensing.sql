-- Artaveo central services (ADR-16): licenses, activation, installations, security events and
-- update metadata. No patient data is ever stored here (ADR-17).
-- Every table has Row Level Security on and no public policy: the desktop app reaches the data only
-- through the Edge Functions (service role); the Vendor Panel reaches it as a signed-in vendor user.

create table vendor_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null,
  created_at timestamptz not null default now()
);

create function is_vendor() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from vendor_users where user_id = auth.uid())
$$;

create table clinics (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  owner_name text,
  phone text,
  city text,
  notes text,
  created_at timestamptz not null default now()
);

create table licenses (
  id uuid primary key default gen_random_uuid(),
  clinic_id uuid not null references clinics (id),
  plan text not null check (plan in ('basic', 'standard', 'pro')),
  status text not null default 'active' check (status in ('active', 'revoked')),
  starts_at timestamptz not null,
  expires_at timestamptz not null,
  offline_grace_days int not null default 30 check (offline_grace_days between 7 and 365),
  revoked_reason text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (expires_at > starts_at)
);
create index licenses_clinic on licenses (clinic_id);

-- One row per installation of the app (the id is generated by the app, never reused).
create table installations (
  id uuid primary key default gen_random_uuid(),
  installation_key text not null unique,
  clinic_id uuid references clinics (id),
  license_id uuid references licenses (id),
  clinic_name text,
  computer_name text,
  app_version text,
  arch text,
  status text not null default 'trial' check (status in ('trial', 'active', 'blocked', 'released')),
  trial_started_at timestamptz,
  trial_expires_at timestamptz,
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  -- Only the day and the outcome of the last backup, for support (roadmap 10.11); never content.
  last_backup_at timestamptz,
  last_backup_ok boolean
);
create index installations_license on installations (license_id);

create table activation_codes (
  id uuid primary key default gen_random_uuid(),
  code_hash text not null unique,
  code_hint text not null,
  clinic_id uuid not null references clinics (id),
  license_id uuid not null references licenses (id),
  max_uses int not null check (max_uses between 1 and 6),
  used int not null default 0,
  expires_at timestamptz not null,
  revoked_at timestamptz,
  created_at timestamptz not null default now()
);

create table security_events (
  id bigint generated always as identity primary key,
  at timestamptz not null default now(),
  kind text not null,
  installation_key text,
  clinic_id uuid,
  detail jsonb not null default '{}'
);
create index security_events_at on security_events (at desc);

create table app_releases (
  version text primary key,
  released_at timestamptz not null default now(),
  -- Oldest app version still allowed to talk to this server / LAN peers.
  min_supported text,
  notes text,
  download_url text,
  signature text,
  channel text not null default 'stable' check (channel in ('stable', 'beta'))
);

alter table vendor_users enable row level security;
alter table clinics enable row level security;
alter table licenses enable row level security;
alter table installations enable row level security;
alter table activation_codes enable row level security;
alter table security_events enable row level security;
alter table app_releases enable row level security;

create policy vendor_all on clinics for all using (is_vendor()) with check (is_vendor());
create policy vendor_all on licenses for all using (is_vendor()) with check (is_vendor());
create policy vendor_all on installations for all using (is_vendor()) with check (is_vendor());
create policy vendor_all on activation_codes for all using (is_vendor()) with check (is_vendor());
create policy vendor_read on security_events for select using (is_vendor());
create policy vendor_all on app_releases for all using (is_vendor()) with check (is_vendor());
create policy vendor_self on vendor_users for select using (user_id = auth.uid());
